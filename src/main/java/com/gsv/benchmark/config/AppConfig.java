package com.gsv.benchmark.config;

import com.mongodb.ConnectionString;
import com.mongodb.MongoClientSettings;
import com.mongodb.client.MongoClient;
import com.mongodb.client.MongoClients;
import com.zaxxer.hikari.HikariConfig;
import com.zaxxer.hikari.HikariDataSource;

import java.io.IOException;
import java.io.InputStream;
import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;
import java.util.Properties;


/**
 * Central configuration hub for the benchmark.
 *
 * <p>Loads base settings from the profile-specific properties file
 * ({@code application-local.properties} or {@code application-prod.properties})
 * and allows any value to be overridden via environment variables.
 *
 * <h3>Profile: local</h3>
 * Plain JDBC connection pool to Docker Compose PostgreSQL; plain MongoDB URI to
 * Docker Compose MongoDB.
 *
 * <h3>Profile: prod</h3>
 * <ul>
 *   <li><b>PostgreSQL (RDS)</b> — HikariCP pool + SSL + IAM auth token generated by
 *       {@link RdsIamTokenProvider} using the instance's IAM role.</li>
 *   <li><b>MongoDB (DocumentDB)</b> — TLS-enabled MongoClient; username and
 *       password supplied via {@code MONGO_USER} / {@code MONGO_PASSWORD} env vars.</li>
 * </ul>
 */
public class AppConfig {

    private final Profile    profile;
    private final Properties props;

    // ------------------------------------------------------------------
    // Construction
    // ------------------------------------------------------------------

    private AppConfig(Profile profile, Properties props) {
        this.profile = profile;
        this.props   = props;
    }

    /**
     * Loads config for the active profile (driven by {@code BENCHMARK_PROFILE} env var).
     */
    public static AppConfig load() throws IOException {
        Profile profile = Profile.resolve();
        String  file    = profile == Profile.PROD
                          ? "/application-prod.properties"
                          : "/application-local.properties";

        Properties props = new Properties();
        try (InputStream is = AppConfig.class.getResourceAsStream(file)) {
            if (is == null) throw new IOException("Properties file not found on classpath: " + file);
            props.load(is);
        }
        return new AppConfig(profile, props);
    }

    // ------------------------------------------------------------------
    // Connection builders
    // ------------------------------------------------------------------

    /**
     * Builds a HikariCP {@link HikariDataSource} for the active profile.
     * Both profiles use plain username/password authentication.
     *
     * <ul>
     *   <li><b>local</b> — plain JDBC URL, no SSL.</li>
     *   <li><b>prod</b>  — SSL enabled (verify-full + RDS CA bundle); plain password
     *       supplied via {@code pg.password} / {@code PG_PASSWORD} env var.</li>
     * </ul>
     */
    public HikariDataSource buildPostgresDataSource() throws Exception {
        String host     = require("pg.host");
        int    port     = Integer.parseInt(get("pg.port", "5432"));
        String db       = get("pg.db", "core_data_db");
        String schema   = getPgSchema();
        String user     = require("pg.user");
        String password = require("pg.password");

        int poolSize = getConcurrentUsers() + getSeedThreads() + 4;

        HikariConfig hikari = new HikariConfig();
        hikari.setUsername(user);
        hikari.setPassword(password);
        hikari.setMaximumPoolSize(poolSize);
        hikari.setMinimumIdle(getSeedThreads());
        hikari.setConnectionTimeout(30_000);
        hikari.setIdleTimeout(600_000);
        hikari.setMaxLifetime(1_800_000);
        hikari.setPoolName("benchmark-pg-pool");

        if (profile == Profile.LOCAL) {
            hikari.setJdbcUrl(String.format(
                "jdbc:postgresql://%s:%d/%s?currentSchema=%s", host, port, db, schema));
        } else {
            // PROD: SSL required for RDS; password supplied via env var PG_PASSWORD
            hikari.setJdbcUrl(String.format(
                "jdbc:postgresql://%s:%d/%s?ssl=true&sslmode=%s&currentSchema=%s",
                host, port, db, get("pg.ssl.mode", "verify-full"), schema));

            String caFile = get("pg.ssl.ca-file", "");
            if (!caFile.isBlank()) {
                hikari.addDataSourceProperty("sslrootcert", caFile);
            }
        }

        return new HikariDataSource(hikari);
    }

    /**
     * Builds a {@link MongoClient} appropriate for the active profile.
     * Pool size is configured to handle concurrent stress test threads.
     */
    public MongoClient buildMongoClient() {
        String host    = require("mongo.host");
        int    port    = Integer.parseInt(get("mongo.port", "27017"));
        int    maxConn = getConcurrentUsers() + getSeedThreads() + 4;

        if (profile == Profile.LOCAL) {
            MongoClientSettings settings = MongoClientSettings.builder()
                .applyConnectionString(new ConnectionString(
                    String.format("mongodb://%s:%d", host, port)))
                .applyToConnectionPoolSettings(pool -> pool.maxSize(maxConn))
                .build();
            return MongoClients.create(settings);
        }

        // PROD: DocumentDB — TLS required, SCRAM auth with env-var credentials
        String user   = encode(require("mongo.user"));
        String pass   = encode(require("mongo.password"));
        String db     = getMongoDb();
        String caFile = get("mongo.tls.ca-file", "");

        // DocumentDB requires retryWrites=false
        StringBuilder uri = new StringBuilder(
            String.format("mongodb://%s:%s@%s:%d/%s?tls=true&retryWrites=false",
                          user, pass, host, port, db));
        if (!caFile.isBlank()) {
            uri.append("&tlsCAFile=").append(encode(caFile));
        }

        MongoClientSettings settings = MongoClientSettings.builder()
            .applyConnectionString(new ConnectionString(uri.toString()))
            .applyToSslSettings(ssl -> ssl.enabled(true))
            .applyToConnectionPoolSettings(pool -> pool.maxSize(maxConn))
            .build();

        return MongoClients.create(settings);
    }

    // ------------------------------------------------------------------
    // Benchmark parameters
    // ------------------------------------------------------------------

    public int     getRecordCount()       { return Integer.parseInt(get("benchmark.record-count",         "1000000")); }
    public int     getWarmup()            { return Integer.parseInt(get("benchmark.warmup",               "5")); }
    public int     getIterations()        { return Integer.parseInt(get("benchmark.iterations",           "500")); }

    // Seeding
    public int     getSeedThreads()       { return Integer.parseInt(get("benchmark.seed-threads",         "4")); }
    public int     getSeedChunkSize()     { return Integer.parseInt(get("benchmark.seed-chunk-size",      "10000")); }
    public int     getPgSeedBatchSize()   { return Integer.parseInt(get("benchmark.pg-seed-batch-size",   "5000")); }
    public int     getMongoSeedBatchSize(){ return Integer.parseInt(get("benchmark.mongo-seed-batch-size","1000")); }
    public int     getInsertPoolSize()    { return Integer.parseInt(get("benchmark.insert-pool-size",     "50000")); }

    // Stress test
    public int     getConcurrentUsers()   { return Integer.parseInt(get("benchmark.concurrent-users",        "20")); }
    public int     getStressDurationSec() { return Integer.parseInt(get("benchmark.stress-duration-seconds", "60")); }
    public int     getStressSelectPct()   { return Integer.parseInt(get("benchmark.stress-select-pct",       "60")); }
    public int     getStressInsertPct()   { return Integer.parseInt(get("benchmark.stress-insert-pct",       "25")); }
    public int     getStressUpdatePct()   { return Integer.parseInt(get("benchmark.stress-update-pct",       "15")); }

    // Database names
    public String  getPgSchema()          { return get("pg.schema",   "benchmark"); }
    public String  getMongoDb()           { return get("mongo.db",    "benchmark"); }
    public Profile getProfile()           { return profile; }

    // ------------------------------------------------------------------
    // Property resolution: file value < env var override
    // ------------------------------------------------------------------

    /**
     * Looks up a property, allowing environment-variable overrides.
     * The env var name is derived by uppercasing and replacing dots/hyphens with underscores.
     * e.g. {@code pg.host} → {@code PG_HOST}.
     */
    private String get(String key, String defaultValue) {
        String envKey = key.toUpperCase().replace('.', '_').replace('-', '_');
        String envVal = System.getenv(envKey);
        if (envVal != null && !envVal.isBlank()) return envVal.trim();
        String propVal = props.getProperty(key);
        return (propVal != null && !propVal.isBlank()) ? propVal.trim() : defaultValue;
    }

    /** Like {@link #get} but throws if the value is absent. */
    private String require(String key) {
        String val = get(key, null);
        if (val == null || val.isBlank()) {
            String envKey = key.toUpperCase().replace('.', '_').replace('-', '_');
            throw new IllegalStateException(
                String.format("Required config '%s' (env: %s) is not set for profile '%s'.",
                              key, envKey, profile));
        }
        return val;
    }

    private static String encode(String s) {
        return URLEncoder.encode(s, StandardCharsets.UTF_8);
    }
}
